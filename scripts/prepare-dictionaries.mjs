import { readFile, mkdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// Embed only the dictionary data: the packages' default entry points use fs,
// which is unavailable in an extension content script.
const require = createRequire(import.meta.url);
const root = fileURLToPath(new URL("../", import.meta.url));
const generated = join(root, "src/generated");
const licenses = join(root, "public/licenses");
await mkdir(generated, { recursive: true });
await mkdir(licenses, { recursive: true });
let source =
  "// Generated by scripts/prepare-dictionaries.mjs. Do not edit.\n" +
  "// SCOWL/Hunspell English dictionaries; full notices: public/licenses/.\n";
for (const [name, exportName] of [
  ["dictionary-en", "americanDictionary"],
  ["dictionary-en-gb", "britishDictionary"],
]) {
  const packageRoot = dirname(require.resolve(name));
  const [aff, dic, license] = await Promise.all(
    ["index.aff", "index.dic", "license"].map((file) =>
      readFile(join(packageRoot, file), "utf8"),
    ),
  );
  source += `export const ${exportName} = ${JSON.stringify({ aff, dic })};\n`;
  await writeFile(join(licenses, `${name}.txt`), license);
}
const nspellRoot = dirname(require.resolve("nspell/package.json"));
await writeFile(
  join(licenses, "nspell.txt"),
  await readFile(join(nspellRoot, "license"), "utf8"),
);
await writeFile(join(generated, "dictionaries.ts"), source);
